# ---------------- Synthetic Noise Generators ----------------

def add_gaussian_noise(arr: np.ndarray, mean: float = 0.0, sigma: float = 25.0) -> np.ndarray:
    """
    Gaussian Noise: n ~ N(mean, sigma^2)
    Additive electronic and sensor thermal noise.
    """
    noise = np.random.normal(mean, sigma, arr.shape)
    noisy = arr.astype(float) + noise
    return np.clip(np.round(noisy), 0, 255).astype(np.uint8)


def add_salt_and_pepper_noise(arr: np.ndarray, amount: float = 0.05, salt_vs_pepper: float = 0.5) -> np.ndarray:
    """
    Salt-and-Pepper (Impulse) Noise:
    Random isolated pixels set to minimum (0, pepper) or maximum (255, salt).
    Caused by faulty sensor pixels, transmission errors, or analog-to-digital converter glitches.
    (Unit 1 Slide 29)
    """
    noisy = arr.copy()
    num_noise = int(arr.size * amount)
    
    # Coordinates to corrupt
    if arr.ndim == 2:
        h, w = arr.shape
        coords = [np.random.randint(0, i - 1, int(num_noise)) for i in arr.shape]
        num_salt = int(num_noise * salt_vs_pepper)
        noisy[coords[0][:num_salt], coords[1][:num_salt]] = 255
        noisy[coords[0][num_salt:], coords[1][num_salt:]] = 0
    else:
        h, w, c = arr.shape
        coords = [np.random.randint(0, i, int(num_noise)) for i in (h, w)]
        num_salt = int(num_noise * salt_vs_pepper)
        noisy[coords[0][:num_salt], coords[1][:num_salt]] = [255, 255, 255]
        noisy[coords[0][num_salt:], coords[1][num_salt:]] = [0, 0, 0]
        
    return noisy


def add_speckle_noise(arr: np.ndarray, var: float = 0.04) -> np.ndarray:
    """
    Speckle Noise: Multiplicative noise n ~ N(0, var)
    I_noisy = I + I * n
    Common in radar, ultrasound, and coherent illumination imaging.
    """
    noise = np.random.normal(0, np.sqrt(var), arr.shape)
    noisy = arr.astype(float) + arr.astype(float) * noise
    return np.clip(np.round(noisy), 0, 255).astype(np.uint8)


def add_poisson_noise(arr: np.ndarray) -> np.ndarray:
    """
    Poisson (Shot) Noise:
    Generated by statistical quantum fluctuations in photon arrival.
    """
    # Scale image to avoid zero rates
    vals = len(np.unique(arr))
    vals = 2 ** np.ceil(np.log2(max(2, vals)))
    noisy = np.random.poisson(arr.astype(float))
    return np.clip(noisy, 0, 255).astype(np.uint8)


# ---------------- Restoration & Comparison Metrics ----------------

def calculate_restoration_metrics(original: np.ndarray, processed: np.ndarray) -> Dict[str, float]:
    """
    Calculates Mean Squared Error (MSE), Peak Signal-to-Noise Ratio (PSNR),
    and Mean Absolute Error (MAE) between pristine original and restored image.
    """
    orig = original.astype(float)
    proc = processed.astype(float)
    
    mse = float(np.mean((orig - proc) ** 2))
    mae = float(np.mean(np.abs(orig - proc)))
    
    if mse < 1e-10:
        psnr = 99.0  # Perfect match
    else:
        max_pixel = 255.0
        psnr = float(20.0 * np.log10(max_pixel / np.sqrt(mse)))
        
    return {
        "mse": round(mse, 2),
        "psnr": round(psnr, 2),
        "mae": round(mae, 2)
    }


# ---------------- Smoothing & Sharpening Filters ----------------

def apply_box_filter(arr: np.ndarray, k_size: int = 3) -> np.ndarray:
    """Mean / Box Filter of size k_size x k_size."""
    kernel = np.ones((k_size, k_size), dtype=float) / float(k_size * k_size)
    return apply_spatial_filter(arr, kernel, padding_mode='replicate', op_type='linear')


def apply_gaussian_filter(arr: np.ndarray, sigma: float = 1.0, k_size: int = 3) -> np.ndarray:
    """
    Gaussian smoothing filter:
    G(x, y) = (1 / (2*pi*sigma^2)) * exp(-(x^2 + y^2) / (2*sigma^2))
    """
    rad = k_size // 2
    y, x = np.mgrid[-rad:rad+1, -rad:rad+1]
    g = np.exp(-(x**2 + y**2) / (2.0 * sigma**2))
    kernel = g / np.sum(g)
    return apply_spatial_filter(arr, kernel, padding_mode='replicate', op_type='linear')


def apply_median_filter(arr: np.ndarray, k_size: int = 3) -> np.ndarray:
    """
    Non-linear median filter: optimal for impulse / salt-and-pepper noise.
    Preserves edges while eliminating outlier noise spikes. (Unit 1 Slide 29)
    """
    kernel = np.ones((k_size, k_size), dtype=float)
    return apply_spatial_filter(arr, kernel, padding_mode='replicate', op_type='median')


def apply_min_filter(arr: np.ndarray, k_size: int = 3) -> np.ndarray:
    """Order-statistic minimum filter."""
    kernel = np.ones((k_size, k_size), dtype=float)
    return apply_spatial_filter(arr, kernel, padding_mode='replicate', op_type='min')


def apply_max_filter(arr: np.ndarray, k_size: int = 3) -> np.ndarray:
    """Order-statistic maximum filter."""
    kernel = np.ones((k_size, k_size), dtype=float)
    return apply_spatial_filter(arr, kernel, padding_mode='replicate', op_type='max')


def apply_bilateral_filter(arr: np.ndarray, d: int = 9, sigma_color: float = 75.0, sigma_space: float = 75.0) -> np.ndarray:
    """
    Bilateral filter: Edge-preserving smoothing filter combining spatial distance
    and radiometric intensity differences.
    """
    if HAS_CV2:
        return cv2.bilateralFilter(arr, d, sigma_color, sigma_space)
    else:
        # Graceful fallback: Gaussian approximation if cv2 not available
        return apply_gaussian_filter(arr, sigma=1.5, k_size=5)


def apply_unsharp_masking(arr: np.ndarray, k: float = 1.0, sigma: float = 1.0) -> Tuple[np.ndarray, np.ndarray]:
    """
    Unsharp Masking:
      1. Blurring: f_blur = GaussianBlur(f)
      2. Mask creation: mask = f - f_blur (captures high-frequency details)
      3. Sharpening: f_sharp = f + k * mask
    Returns (sharpened_image, unsharp_mask).
    """
    blurred = apply_gaussian_filter(arr, sigma=sigma, k_size=3)
    orig_f = arr.astype(float)
    blur_f = blurred.astype(float)
    mask = orig_f - blur_f
    
    sharpened = orig_f + k * mask
    out_sharp = np.clip(np.round(sharpened), 0, 255).astype(np.uint8)
    
    # Normalized mask for visualization (128 = zero difference)
    disp_mask = np.clip(np.round(mask + 128), 0, 255).astype(np.uint8)
    return out_sharp, disp_mask
